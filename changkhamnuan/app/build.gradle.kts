  // Release signing is read only from environment variables / an external keystore.
  // Never commit the keystore or its passwords. Without them, release builds are unsigned
  // and debug builds use the standard Android debug key.
  val releaseKeystore = System.getenv("KEYSTORE_PATH")?.let { file(it) }
  val hasReleaseKeystore = releaseKeystore?.exists() == true &&
    !System.getenv("STORE_PASSWORD").isNullOrEmpty() &&
    !System.getenv("KEY_PASSWORD").isNullOrEmpty()
  signingConfigs {
    if (hasReleaseKeystore) {
      create("release") {
        storeFile = releaseKeystore
        storePassword = System.getenv("STORE_PASSWORD")
        keyAlias = System.getenv("KEY_ALIAS") ?: "upload"
        keyPassword = System.getenv("KEY_PASSWORD")
      }
    }
  }

  buildTypes {
    release {
      isCrunchPngs = false
      isMinifyEnabled = true
      isShrinkResources = true
      proguardFiles(getDefaultProguardFile("proguard-android-optimize.txt"), "proguard-rules.pro")
      if (hasReleaseKeystore) {
        signingConfig = signingConfigs.getByName("release")
      } else if (System.getenv("RELEASE_TEST_SIGN") == "1") {
        // CI only: sign the minified release build with the debug key so it can be
        // installed on the emulator. Never used for the store upload.
        signingConfig = signingConfigs.getByName("debug")
      }
    }
  }
